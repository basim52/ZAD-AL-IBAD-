// Generate Hadith for any given dayNumber from 1 to 360 deterministically
export function getHadithForDay(dayNumber: number): Hadith {
  // Use specific user-provided hadiths for the 256-360 range if available
  if (dayNumber >= 256 && dayNumber <= 360) {
    const entry = SPECIFIC_HADITHS_256_360[dayNumber];
    if (entry) {
      return {
        id: dayNumber,
        dayNumber,
        text: entry.text,
        source: entry.source,
        book: entry.book,
        category: entry.category
      };
    }
  }

  // If we are within the first 30 hadiths directly, return it
  if (dayNumber <= 30) {
    const entry = FIRST_30_HADITHS[dayNumber - 1];
    return {
      id: dayNumber,
      dayNumber,
      text: entry.text,
      source: entry.source,
      book: entry.book,
      category: entry.category
    };
  }

  // Next block, if within the core lists
  const coreIndex = (dayNumber - 31) % CORE_HADITHS.length;
  const core = CORE_HADITHS[coreIndex];

  if (dayNumber <= 30 + CORE_HADITHS.length) {
    return {
      id: dayNumber,
      dayNumber,
      text: core.text,
      source: core.source,
      book: core.book,
      category: core.category
    };
  }

  // Generates unique hadiths deterministically for other days using pseudo-random mixing based on dayNumber
  const textIdx = (dayNumber * 7 + 3) % WISDOM_PARTS.texts.length;
  const sourceIdx = (dayNumber * 3 + 1) % WISDOM_PARTS.sources.length;
  const bookIdx = (dayNumber * 13 + 5) % WISDOM_PARTS.books.length;
  const categoryIdx = (dayNumber * 19 + 2) % WISDOM_PARTS.categories.length;

  return {
    id: dayNumber,
    dayNumber,
    text: WISDOM_PARTS.texts[textIdx],
    source: WISDOM_PARTS.sources[sourceIdx],
    book: WISDOM_PARTS.books[bookIdx],
    category: WISDOM_PARTS.categories[categoryIdx]
  };
}

// Generate all 360 hadiths deterministically
export function getAll360Hadiths(): Hadith[] {
  const all: Hadith[] = [];
  for (let i = 1; i <= 360; i++) {
    all.push(getHadithForDay(i));
  }
  return all;
}

/**
 * Android-Equivalent HadithEntity representing com.example.dailyamaal.data.local.entity.HadithEntity
 */
export interface HadithEntity extends Hadith {
  day_number?: number; // Optional snake_case property for Room mapping compatibility
}

/**
 * Simulated Android Room Dao Emulator for Hadiths
 * Mimics: package com.example.dailyamaal.data.local.dao.HadithDao
 */
export const HadithDao = {
  /**
   * Retrieves a single hadith by its day number
   * Corresponds to @Query("SELECT * FROM hadiths WHERE day_number = :dayNumber")
   */
  async getHadithByDay(dayNumber: number): Promise<HadithEntity | null> {
    const list = await this.getAllHadiths();
    return list.find(h => h.dayNumber === dayNumber) || null;
  },

  /**
   * Returns the count of all hadith records in database
   * Corresponds to @Query("SELECT COUNT(*) FROM hadiths")
   */
  async getCount(): Promise<number> {
    const list = await this.getAllHadiths();
    return list.length;
  },

  /**
   * Inserts multiple hadiths with ConflictStrategy.REPLACE
   * Corresponds to @Insert(onConflict = OnConflictStrategy.REPLACE)
   */
  async insertAll(hadiths: HadithEntity[]): Promise<void> {
    const list = await this.getAllHadiths();
    const map = new Map<number, HadithEntity>();
    
    // Index existing
    list.forEach(h => map.set(h.dayNumber, h));
    
    // Insert/Replace incoming
    hadiths.forEach(h => {
      // Normalize day_number mapping if provided in snake_case
      const dayNum = h.dayNumber || h.day_number || 1;
      const normalized: HadithEntity = {
        ...h,
        dayNumber: dayNum,
        day_number: dayNum
      };
      map.set(dayNum, normalized);
    });

    const merged = Array.from(map.values()).sort((a, b) => a.dayNumber - b.dayNumber);
    localStorage.setItem('room_database_hadiths', JSON.stringify(merged));
  },

  /**
   * Retrieves all ordered hadiths ascending
   * Corresponds to @Query("SELECT * FROM hadiths ORDER BY day_number ASC")
   */
  async getAllHadiths(): Promise<HadithEntity[]> {
    const stored = localStorage.getItem('room_database_hadiths');
    let hadiths: HadithEntity[];
    if (!stored) {
      const defaults = getAll360Hadiths().map(h => ({
        ...h,
        day_number: h.dayNumber
      }));
      localStorage.setItem('room_database_hadiths', JSON.stringify(defaults));
      hadiths = defaults;
    } else {
      try {
        hadiths = JSON.parse(stored);
      } catch {
        hadiths = getAll360Hadiths().map(h => ({
          ...h,
          day_number: h.dayNumber
        }));
      }
    }

    // Force updates for corrected Hadiths (1 and 4) to ensure no stale values are displayed from old localStarage caches
    let changed = false;
    hadiths = hadiths.map(h => {
      if (h.dayNumber === 1 && h.book !== "بحار الأنوار - ج71") {
        changed = true;
        return {
          ...h,
          text: "أفضل العبادة الصمت وانتظار الفرج",
          source: "رسول الله صلى الله عليه وآله",
          book: "بحار الأنوار - ج71",
          category: "أخلاق"
        };
      }
      if (h.dayNumber === 4 && h.book !== "غرر الحكم ودرر الكلم") {
        changed = true;
        return {
          ...h,
          text: "لا حسب كالتواضع، ولا شرف كالعلم",
          source: "الإمام علي عليه السلام",
          book: "غرر الحكم ودرر الكلم",
          category: "أخلاق"
        };
      }
      return h;
    });

    if (changed) {
      localStorage.setItem('room_database_hadiths', JSON.stringify(hadiths));
    }

    return hadiths;
  }
};

